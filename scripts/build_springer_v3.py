#!/usr/bin/env python3
"""
Build the Springer Nature (sn-jnl) version of paper/main_v3.tex for Natural Resources Research.

Source of truth: paper/main_v3.tex (elsarticle working copy). Author/affiliation block taken
from paper/springer/main_esin.tex (already in sn-jnl syntax). Output: paper/springer_v3/
(main_nrr.tex, figures copied flat, sn-jnl.cls, sn-basic.bst, references_v2.bib).
NRR requires a "Statements and Declarations" section before the references; the starred
back-matter sections of main_v3 are moved there. Run after ANY edit to main_v3.tex.
"""
import re, shutil
from pathlib import Path

P = Path(__file__).resolve().parent.parent / "paper"
OUT = P / "springer_v3"; OUT.mkdir(exist_ok=True)
v3 = (P / "main_v3.tex").read_text()
esin = (P / "springer" / "main_esin.tex").read_text()

title = re.search(r"\\title\{(.*?)\}\n", v3).group(1)
authors = re.search(r"(\\author\*\[1\].*?)\n\n\\abstract", esin, re.S).group(1)
abstract = re.search(r"\\begin\{abstract\}\n(.*?)\n\\end\{abstract\}", v3, re.S).group(1)
kw = re.search(r"\\begin\{keyword\}\n(.*?)\n\\end\{keyword\}", v3, re.S).group(1).replace(" \\sep ", ", ")
body = v3[v3.index("\\section{Introduction}"):v3.index("\\section*{Data availability}")]
back = v3[v3.index("\\section*{Data availability}"):v3.index("\\bibliographystyle")]

# figures: copy flat, rewrite paths
for f in sorted(set(re.findall(r"\{\.\./figures/v2/([^}]+)\}", body))):
    shutil.copy(P.parent / "figures" / "v2" / f, OUT / f)
body = body.replace("../figures/v2/", "")
# sn-jnl wraps table contents in its own environments: \resizebox/adjustbox break them.
# Medium tables: small font + fixed-width text columns. The two wide tables: sidewaystable.
def _wide_to_sideways(body, label):
    i = body.index("\\label{" + label + "}"); a = body.rfind("\\begin{table*}", 0, i); b = body.index("\\end{table*}", i)
    blk = body[a:b + len("\\end{table*}")].replace("\\begin{table*}[ht]", "\\begin{sidewaystable}").replace("\\end{table*}", "\\end{sidewaystable}")
    return body[:a] + blk + body[b + len("\\end{table*}"):]
for lab in ("tab:criteria", "tab:main"):
    body = _wide_to_sideways(body, lab)
body = re.sub(r"\\resizebox\{\\(?:text|column)width\}\{!\}\{%\n", lambda m: "\\footnotesize\\setlength{\\tabcolsep}{3pt}\n", body)
body = body.replace("\\end{tabular}}", "\\end{tabular}")
body = body.replace("\\begin{tabular}{lllrrr}", "\\begin{tabular}{llp{3.3cm}rp{2.1cm}r}")
body = body.replace("\\begin{tabular}{llrrrr}", "\\begin{tabular}{lp{3.2cm}rrrr}")

# back matter -> Statements and Declarations
parts = dict(re.findall(r"\\section\*\{(.*?)\}\n\n(.*?)(?=\n\\section\*|\Z)", back, re.S))
decl = "\\section*{Statements and Declarations}\n\n"
for head in ["Funding", "Declaration of competing interest", "CRediT authorship contribution statement", "Data availability"]:
    name = {"Declaration of competing interest": "Competing interests", "CRediT authorship contribution statement": "Author contributions",
            "Data availability": "Data availability"}.get(head, head)
    decl += f"\\bmhead{{{name}}}\n{parts[head].strip()}\n\n"
decl += "\\bmhead{Use of generative AI}\nThe use of a large language model in drafting the manuscript is declared in Section~\\ref{sec:methods}.\n\n"
ack = "\\bmhead{Acknowledgements}\n" + parts["Acknowledgements"].strip() + "\n\n"

tex = f"""%% Natural Resources Research (Springer Nature) submission
%% GENERATED by scripts/build_springer_v3.py from paper/main_v3.tex -- edit main_v3.tex, not this file.
\\documentclass[pdflatex,sn-basic]{{sn-jnl}}
\\usepackage{{graphicx}}
\\usepackage{{multirow}}
\\usepackage{{amsmath,amssymb,amsfonts}}
\\usepackage{{booktabs}}
\\usepackage{{xcolor}}
\\usepackage{{siunitx}}
\\usepackage{{rotating}}
\\hypersetup{{bookmarksdepth=3}}
\\setlength{{\\emergencystretch}}{{3em}}
\\raggedbottom

\\begin{{document}}

\\title{{{title}}}

{authors}

\\abstract{{{abstract}}}

\\keywords{{{kw}}}

\\maketitle

{body}
{ack}{decl}
\\bibliography{{references_v2}}

\\end{{document}}
"""
(OUT / "main_nrr.tex").write_text(tex)
for f in ["sn-jnl.cls", "sn-basic.bst"]:
    shutil.copy(P / "springer" / f, OUT / f)
shutil.copy(P / "references_v2.bib", OUT / "references_v2.bib")
shutil.copy(P / "highlights_v3.txt", OUT / "highlights.txt")
print("written", OUT / "main_nrr.tex")
